export const getAiMockJobs = () =>
  MOCK_JOBS.filter(j =>
    j.title.toLowerCase().includes('ai') || 
    j.title.toLowerCase().includes('machine learning') || 
    j.skills.some(s => ['python', 'pytorch', 'tensorflow', 'llms', 'prompt engineering', 'generative ai', 'transformers'].includes(s.toLowerCase()))
  )

export const getFresherMockJobs = () => MOCK_JOBS.filter(j => j.experienceLevel === 'fresher')

export const getFeaturedMockJobs = () => MOCK_JOBS.filter(j => j.isFeatured)
